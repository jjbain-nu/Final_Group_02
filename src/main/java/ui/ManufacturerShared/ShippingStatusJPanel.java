    public void populateTable() {
        DefaultTableModel model = (DefaultTableModel) shippingTable.getModel();
        model.setRowCount(0);
        for (WorkRequest wr : organization.getWorkQueue().getWorkRequestList()) {
            if (!(wr instanceof DeliveryWorkRequest)) {
                continue;
            }
            DeliveryWorkRequest dwr = (DeliveryWorkRequest) wr;
            model.addRow(new Object[]{
                dwr.getCargoDescription(),
                dwr.getDropLocation(),
                dwr.getStatus(),
                dwr.getDeliveryReport() == null ? "" : dwr.getDeliveryReport()
            });
        }
    }

