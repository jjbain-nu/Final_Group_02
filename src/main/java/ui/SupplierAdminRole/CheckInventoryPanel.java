    private void populateInventoryTable() {
           DefaultTableModel model = (DefaultTableModel) tblInventory.getModel();
        
        model.setRowCount(0);
        for (MaterialInventory mi : organization.getMaterialInventoryDirectory().getInventoryList()){
            
            Object[] row = new Object[4];
            row[0] = mi.getMaterial();
            row[1] = mi.getMaterial().getMaterialName();
            row[2] = mi.getAvailableQty();
            row[3] = mi.getPickingQty();
            
            model.addRow(row);
            }
    
    
    }

