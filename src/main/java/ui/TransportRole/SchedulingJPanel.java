    private void assignJButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_assignJButtonActionPerformed
        // TODO add your handling code here:
         int row = requestJTable.getSelectedRow();
        if (row < 0) { JOptionPane.showMessageDialog(this, "Pick a request first."); return; }
        Truck t = (Truck) truckJComboBox.getSelectedItem();
        if (t == null) { JOptionPane.showMessageDialog(this, "No available truck selected."); return; }
        Date scheduled;
        try { scheduled = sdf.parse(dateJTextField.getText().trim()); }
        catch (Exception ex) { JOptionPane.showMessageDialog(this, "Date must be yyyy-MM-dd"); return; }
        DeliveryWorkRequest d = (DeliveryWorkRequest) requestJTable.getValueAt(row, 0);
        d.setScheduledDate(scheduled);
        d.setAssignedTruck(t);
        d.setStatus(DeliveryWorkRequest.STATUS_ASSIGNED);
        t.setStatus(Truck.STATUS_ASSIGNED);
        populateRequestTable();
        populateTruckCombo();
        JOptionPane.showMessageDialog(this, "Scheduled and truck assigned.");
    }//GEN-LAST:event_assignJButtonActionPerformed

