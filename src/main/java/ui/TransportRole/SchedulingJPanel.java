    public void populateRequestTable() {
        DefaultTableModel m = (DefaultTableModel) requestJTable.getModel();
        m.setRowCount(0);
        for (WorkRequest r : organization.getWorkQueue().getWorkRequestList()) {
            if (!(r instanceof DeliveryWorkRequest)) continue;
            DeliveryWorkRequest d = (DeliveryWorkRequest) r;
            if (DeliveryWorkRequest.STATUS_COMPLETED.equals(d.getStatus())
                    || DeliveryWorkRequest.STATUS_REPORTED.equals(d.getStatus())) continue;
            m.addRow(new Object[]{d, d.getPickupLocation(), d.getDropLocation(),
                d.getScheduledDate() == null ? "" : sdf.format(d.getScheduledDate()),
                d.getAssignedTruck(), d.getStatus()});
        }
    }

    private void populateTruckCombo() {
        truckJComboBox.removeAllItems();
        for (Truck t : organization.getFleetDirectory().getTruckList()) {
            if (Truck.STATUS_AVAILABLE.equals(t.getStatus())) truckJComboBox.addItem(t);
        }
    }

