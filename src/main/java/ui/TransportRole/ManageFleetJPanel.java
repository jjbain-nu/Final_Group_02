    public void populateTable() {
        DefaultTableModel m = (DefaultTableModel) fleetJTable.getModel();
        m.setRowCount(0);
        for (Truck t : organization.getFleetDirectory().getTruckList()) {
            m.addRow(new Object[]{t, t.getLicensePlate(), t.getModel(),
                t.getCapacityKg(), t.getStatus()});
        }
    }

