    private void btnCreateAccountActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCreateAccountActionPerformed
        // TODO add your handling code here:
        String name = txtFullName.getText().trim();
        String nuid = txtNUID.getText().trim();
        String un   = txtUsername.getText().trim();
        String pw   = new String(jPasswordField1.getPassword()).trim();

        if (name.isEmpty() || nuid.isEmpty() || un.isEmpty() || pw.isEmpty()) {
            JOptionPane.showMessageDialog(this, "All fields are required.", "Missing info",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (business.getUserAccountDirectory().findByUsername(un) != null) {
            JOptionPane.showMessageDialog(this, "That username is taken.", "Taken",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }

        StudentProfile existing = business.getStudentDirectory().findStudentByNuid(nuid);
        if (existing != null) {
            // Admin pre-registered this NUID. If it already has a login, stop; else attach one.
            if (business.getUserAccountDirectory()
                    .findUserAccount(existing.getPerson().getPersonId()) != null) {
                JOptionPane.showMessageDialog(this,
                        "An account for this NUID already exists. Please log in.",
                        "Exists", JOptionPane.ERROR_MESSAGE);
                return;
            }
            existing.getPerson().setName(name);
            business.getUserAccountDirectory().newUserAccount(existing, un, pw);
        } else {
            // Brand-new student
            Person person = business.getPersonDirectory().newPerson(name);
            StudentProfile sp = business.getStudentDirectory().newStudentProfile(person);
            sp.setNuid(nuid);
            business.getUserAccountDirectory().newUserAccount(sp, un, pw);
        }

        JOptionPane.showMessageDialog(this, "Account created. You can now log in.", "Done",
                JOptionPane.INFORMATION_MESSAGE);
        CardSequencePanel.remove(this);
        ((java.awt.CardLayout) CardSequencePanel.getLayout()).next(CardSequencePanel);
        
    }//GEN-LAST:event_btnCreateAccountActionPerformed


