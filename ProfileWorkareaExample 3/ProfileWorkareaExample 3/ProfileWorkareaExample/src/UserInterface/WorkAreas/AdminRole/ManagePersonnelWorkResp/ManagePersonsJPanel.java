    private void btnRegisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegisterActionPerformed
        // TODO add your handling code here:
        String id    = txtId.getText().trim();
        String name  = txtName.getText().trim();
        String un    = txtUsername.getText().trim();
        String pw    = txtPassword.getText().trim();

        if (id.isEmpty() || name.isEmpty() || un.isEmpty() || pw.isEmpty()) {
            JOptionPane.showMessageDialog(this, "ID, Name, Username and Password are required.",
                    "Missing info", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (business.getPersonDirectory().findPerson(id) != null) {
            JOptionPane.showMessageDialog(this, "That Person ID already exists.", "Duplicate",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (business.getUserAccountDirectory().findByUsername(un) != null) {
            JOptionPane.showMessageDialog(this, "That username is taken.", "Duplicate",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }
        Person person = business.getPersonDirectory()
                .newPerson(id, name, txtEmail.getText().trim(), txtPhone.getText().trim());
        EmployeeProfile ep = business.getEmployeeDirectory().newEmployeeProfile(person);
        ep.setDepartment(txtDepartment.getText().trim());
        ep.setTitle(txtTitle.getText().trim());
        business.getUserAccountDirectory().newUserAccount(ep, un, pw);

        JOptionPane.showMessageDialog(this, "Employee registered.", "Saved",
                JOptionPane.INFORMATION_MESSAGE);
        txtId.setText(""); txtName.setText(""); txtEmail.setText(""); txtPhone.setText("");
        txtDepartment.setText(""); txtTitle.setText(""); txtUsername.setText(""); txtPassword.setText("");
    }//GEN-LAST:event_btnRegisterActionPerformed


