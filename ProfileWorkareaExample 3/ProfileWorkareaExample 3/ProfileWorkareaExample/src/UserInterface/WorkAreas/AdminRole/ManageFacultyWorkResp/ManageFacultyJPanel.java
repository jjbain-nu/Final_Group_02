    private void refreshTable() {
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);
        for (FacultyProfile fp : business.getFacultyDirectory().getFacultyList()) {
            UserAccount ua = business.getUserAccountDirectory()
                    .findUserAccount(fp.getPerson().getPersonId());
            model.addRow(new Object[]{ fp.getPerson().getName(), fp.getDepartment(),
                    fp.getTitle(), ua == null ? "(no login)" : ua.getUserLoginName() });
        }
    }

