    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        // TODO add your handling code here:
        int row = jTable1.getSelectedRow();
        if (row < 0) return;
        selectedFaculty = business.getFacultyDirectory().getFacultyList().get(row);
        txtName.setText(selectedFaculty.getPerson().getName());
        txtDepartment.setText(selectedFaculty.getDepartment());
        txtTitle.setText(selectedFaculty.getTitle());
        UserAccount ua = business.getUserAccountDirectory()
                .findUserAccount(selectedFaculty.getPerson().getPersonId());
        txtUsername.setText(ua == null ? "" : ua.getUserLoginName());
        txtPassword.setText(ua == null ? "" : ua.getPassword());
    }//GEN-LAST:event_jTable1MouseClicked


