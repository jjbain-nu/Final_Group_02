    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        if (selectedFaculty == null) {
            JOptionPane.showMessageDialog(this, "Select a faculty member first.", "No selection",
                    JOptionPane.WARNING_MESSAGE); return;
        }
        selectedFaculty.getPerson().setName(txtName.getText().trim());
        selectedFaculty.setDepartment(txtDepartment.getText().trim());
        selectedFaculty.setTitle(txtTitle.getText().trim());
        refreshTable();
        JOptionPane.showMessageDialog(this, "Faculty updated.", "Saved", JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        if (selectedFaculty == null) {
            JOptionPane.showMessageDialog(this, "Select a faculty member first.", "No selection",
                    JOptionPane.WARNING_MESSAGE); return;
        }
        UserAccount ua = business.getUserAccountDirectory()
                .findUserAccount(selectedFaculty.getPerson().getPersonId());
        if (ua != null) business.getUserAccountDirectory().removeUserAccount(ua);
        business.getFacultyDirectory().removeFaculty(selectedFaculty);
        selectedFaculty = null;
        refreshTable();
        JOptionPane.showMessageDialog(this, "Faculty deleted.", "Deleted", JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnAddFacultyActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddFacultyActionPerformed
        // TODO add your handling code here:
        String name = txtName.getText().trim();
        String un = txtUsername.getText().trim();
        String pw = txtPassword.getText().trim();
        if (name.isEmpty() || un.isEmpty() || pw.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Name, Username and Password are required.",
                    "Missing info", JOptionPane.WARNING_MESSAGE); return;
        }
        if (business.getUserAccountDirectory().findByUsername(un) != null) {
            JOptionPane.showMessageDialog(this, "That username is taken.", "Duplicate",
                    JOptionPane.ERROR_MESSAGE); return;
        }
        Person person = business.getPersonDirectory().newPerson(name);
        FacultyProfile fp = business.getFacultyDirectory().newFacultyProfile(person);
        fp.setDepartment(txtDepartment.getText().trim());
        fp.setTitle(txtTitle.getText().trim());
        business.getUserAccountDirectory().newUserAccount(fp, un, pw);
        refreshTable();
        JOptionPane.showMessageDialog(this, "Faculty added.", "Saved", JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_btnAddFacultyActionPerformed

