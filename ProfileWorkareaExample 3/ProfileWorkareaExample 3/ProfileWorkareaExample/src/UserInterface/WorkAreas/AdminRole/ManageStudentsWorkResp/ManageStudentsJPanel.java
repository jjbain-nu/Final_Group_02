    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        if (selectedStudent == null) {
            JOptionPane.showMessageDialog(this, "Select a student first.", "No selection",
                    JOptionPane.WARNING_MESSAGE); return;
        }
        UserAccount ua = business.getUserAccountDirectory()
                .findUserAccount(selectedStudent.getPerson().getPersonId());
        if (ua != null) business.getUserAccountDirectory().removeUserAccount(ua);
        business.getStudentDirectory().removeStudent(selectedStudent);
        selectedStudent = null;
        refreshTable();
        JOptionPane.showMessageDialog(this, "Student deleted.", "Deleted", JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnAddStudentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddStudentActionPerformed
        // TODO add your handling code here:
        String name = txtName.getText().trim();
        String nuid = txtNUID.getText().trim();
        if (name.isEmpty() || nuid.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Enter a name and an NUID.", "Missing info",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (business.getStudentDirectory().findStudentByNuid(nuid) != null) {
            JOptionPane.showMessageDialog(this, "That NUID already exists.", "Duplicate",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }
        Person person = business.getPersonDirectory().newPerson(name);
        StudentProfile sp = business.getStudentDirectory().newStudentProfile(person);
        sp.setNuid(nuid);
        txtName.setText(""); txtNUID.setText("");
        refreshTable();
        JOptionPane.showMessageDialog(this, "Student added.", "Saved", JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_btnAddStudentActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        if (selectedStudent == null) {
            JOptionPane.showMessageDialog(this, "Select a student first.", "No selection",
                    JOptionPane.WARNING_MESSAGE); return;
        }
        selectedStudent.getPerson().setName(txtName.getText().trim());
        selectedStudent.setNuid(txtNUID.getText().trim());
        refreshTable();
        JOptionPane.showMessageDialog(this, "Student updated.", "Saved", JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        // TODO add your handling code here:
        int row = jTable1.getSelectedRow();
        if (row < 0) return;
        selectedStudent = business.getStudentDirectory()
                .findStudentByNuid((String) jTable1.getValueAt(row, 1));
        if (selectedStudent != null) {
            txtName.setText(selectedStudent.getPerson().getName());
            txtNUID.setText(selectedStudent.getNuid());
        }
    }//GEN-LAST:event_jTable1MouseClicked


