    private void refreshTable() {
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);
        for (StudentProfile sp : business.getStudentDirectory().getStudentList()) {
            boolean hasAccount =
                business.getUserAccountDirectory().findUserAccount(sp.getPerson().getPersonId()) != null;
            model.addRow(new Object[]{ sp.getPerson().getName(), sp.getNuid(),
                                       hasAccount ? "Yes" : "No (can sign up)" });
        }
    }

